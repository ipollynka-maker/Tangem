// spec-to-motion.js — converts pipeline spec → Motion (Framer Motion) React component
'use strict';

// Motion transition for each easing type
function easingToTransition(layer) {
  if (layer.easing === 'spring_bounce' || layer.easing === 'spring_overshoot') {
    const s = layer.spring || {};
    return {
      type: 'spring',
      stiffness: s.stiffness || 200,
      damping:   s.damping   || (layer.easing === 'spring_overshoot' ? 24 : 14),
      mass:      s.mass      || 1,
    };
  }
  const EASE_CURVES = {
    ease_in_out: [0.4, 0, 0.6, 1],
    ease_out:    [0, 0, 0.2, 1],
    ease_in:     [0.4, 0, 1, 1],
    linear:      'linear',
  };
  return {
    type: 'tween',
    ease: EASE_CURVES[layer.easing] || [0, 0, 0.2, 1],
    duration: null, // filled in per layer
  };
}

// Spec property → Motion animate prop
const PROP_MAP = {
  translateX:   'x',
  translateY:   'y',
  translateZ:   'z',
  rotateX:      'rotateX',
  rotateY:      'rotateY',
  rotateZ:      'rotateZ',
  scale:        'scale',
  scaleX:       'scaleX',
  scaleY:       'scaleY',
  opacity:      'opacity',
  width:        'width',
  height:       'height',
  borderRadius: 'borderRadius',
};

function frameToSec(frame, fps) {
  return +(frame / fps).toFixed(3);
}

function layerDuration(layer, spec) {
  if (layer.frame_range) {
    return frameToSec(layer.frame_range[1] - layer.frame_range[0], spec.fps);
  }
  if (layer.phase && spec.phases) {
    const phase = spec.phases.find(p => p.id === layer.phase);
    if (phase) return +(phase.end - phase.start).toFixed(3);
  }
  return spec.duration;
}

function layerDelay(layer, spec) {
  if (layer.start_at != null) return layer.start_at;
  if (layer.frame_range) return frameToSec(layer.frame_range[0], spec.fps);
  if (layer.phase && spec.phases) {
    const phase = spec.phases.find(p => p.id === layer.phase);
    if (phase) return phase.start;
  }
  return 0;
}

function toCamel(str) {
  return str.replace(/-([a-z])/g, (_, c) => c.toUpperCase());
}

function toPascal(name) {
  return name.split('-').map(w => w[0].toUpperCase() + w.slice(1)).join('');
}

function indent(str, n) {
  const pad = ' '.repeat(n);
  return str.split('\n').map(l => pad + l).join('\n');
}

function specToMotionTsx(spec) {
  const componentName = toPascal(spec.name);
  const layers = (spec.layers || []).filter(l => l.render_compatible !== false);

  // Group layers by element id
  const byId = {};
  for (const layer of layers) {
    if (!byId[layer.id]) byId[layer.id] = [];
    byId[layer.id].push(layer);
  }

  // Build per-element animate/initial/transition props
  const elements = Object.entries(byId).map(([id, idLayers]) => {
    const initial = {};
    const animate = {};
    const transition = {};

    for (const layer of idLayers) {
      const prop = PROP_MAP[layer.property] || layer.property;

      if (layer.from != null) initial[prop] = layer.from;
      if (layer.to   != null) animate[prop] = layer.to;

      if (layer.keyframes) {
        animate[prop] = layer.keyframes;
        const dur = layerDuration(layer, spec);
        const delay = layerDelay(layer, spec);
        const t = easingToTransition(layer);
        transition[prop] = { ...t, duration: dur, delay, times: layer.keyframe_positions };
      } else {
        const dur = layerDuration(layer, spec);
        const delay = layerDelay(layer, spec);
        const t = easingToTransition(layer);
        if (t.type === 'tween') t.duration = dur;
        if (delay > 0) t.delay = delay;
        transition[prop] = t;
      }
    }

    const className = toCamel(id);
    const initialStr  = JSON.stringify(initial);
    const animateStr  = JSON.stringify(animate);
    const transitionStr = JSON.stringify(transition, null, 2)
      .split('\n').map((l, i) => i === 0 ? l : '      ' + l).join('\n');

    return `      <motion.div
        className="${className}"
        initial={${initialStr}}
        animate={${animateStr}}
        transition={${transitionStr}}
      />`;
  });

  return `import { motion } from 'motion/react';

/**
 * ${spec.name}
 * Generated by the animate pipeline. Edit freely.
 *
 * Duration: ${spec.duration}s  FPS: ${spec.fps}
 * Install: npm install motion
 */
export function ${componentName}() {
  return (
    <div
      className="animation-root"
      style={{ width: ${spec.width || 800}, height: ${spec.height || 600}, position: 'relative' }}
    >
${elements.join('\n')}
    </div>
  );
}
`;
}

module.exports = { specToMotionTsx };
